"""Upgrading a scaffold (A2C v1.2, wave C design note C-02, item A-6).

Every `aidlc-build` writes `<project>/.a2c/manifest.json`: the A2C version, the request
and the SHA-256 of every generated file (paths relative to the repository root, so the
root workflows of a monorepo are included). `aidlc-build --upgrade <project>` then:

  1. regenerates the request with the installed (new) version into a temporary folder;
  2. replaces every file you have not changed (its hash equals the manifest);
  3. adds files the new version generates for the first time;
  4. for every file you have changed, writes a unified diff to `a2c-upgrade.patch`
     (from the old generated file to the new one, when a baseline is given; otherwise
     from your file to the new generated one) for you to review and apply;
  5. never touches a file that is not in the manifest, and never deletes one.

A project scaffolded before v1.2 has no manifest: pass `--baseline <dir>`, a folder
where the project's original A2C version regenerated the same request (the
aidlc-upgrade workflow does this with the version you name).
"""
import copy
import difflib
import hashlib
import json
import tempfile
from importlib import metadata
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional

MANIFEST = Path('.a2c') / 'manifest.json'
VOLATILE = {'docs/aidlc/build-report.json'}
SKIP_DIRS = {'.a2c', '.git', '.venv', '__pycache__', 'target', '.terraform', 'node_modules', '.pytest_cache'}


class UpgradeError(RuntimeError):
    """The upgrade cannot proceed safely."""


def a2c_version() -> str:
    try:
        return metadata.version('a2c-framework')
    except metadata.PackageNotFoundError:          # running from a checkout
        return 'unknown'


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generated_files(output: Path, project: str) -> Dict[str, str]:
    """{path relative to the repository root: sha256} of a build of `project` in `output`."""
    files = {}
    root = Path(output) / project
    for p in sorted(root.rglob('*')):
        rel = p.relative_to(root)
        if p.is_file() and not (SKIP_DIRS & set(rel.parts)) and rel.as_posix() not in VOLATILE:
            files[f'{project}/{rel.as_posix()}'] = sha(p)
    for p in sorted((Path(output) / '.github' / 'workflows').glob(f'{project}-*.yml')):
        files[p.relative_to(output).as_posix()] = sha(p)
    return files


def clean_request(request: Dict[str, Any]) -> Dict[str, Any]:
    """The request as the user wrote it (the CLI's own additions removed)."""
    r = copy.deepcopy(request)
    r.pop('_request_dir', None)
    r.get('context', {}).pop('contract_schemas', None)
    return r


def write_manifest(output: Path, project: str, request: Dict[str, Any]) -> Path:
    path = Path(output) / project / MANIFEST
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({'generator': 'a2c-framework', 'version': a2c_version(),
                                'request': clean_request(request),
                                'files': generated_files(output, project)}, indent=2, sort_keys=True) + '\n',
                    encoding='utf-8')
    return path


def _text(path: Path) -> List[str]:
    return path.read_text(encoding='utf-8', errors='replace').splitlines(keepends=True)


def upgrade(project_dir: Path, build: Callable[[Dict[str, Any], Path], Dict[str, Any]],
            request: Optional[Dict[str, Any]] = None, baseline: Optional[Path] = None) -> Dict[str, Any]:
    """Bring a scaffold to the installed A2C version. `build(request, output)` is aidlc-build."""
    project_dir = Path(project_dir).resolve()
    repo, project = project_dir.parent, project_dir.name
    manifest_path = project_dir / MANIFEST
    manifest = json.loads(manifest_path.read_text(encoding='utf-8')) if manifest_path.is_file() else None
    if manifest is None and baseline is None:
        raise UpgradeError(f'{project}: no {MANIFEST}; pass --baseline <dir> (the same request regenerated by '
                           'the A2C version that scaffolded the project)')
    request = request or (manifest or {}).get('request')
    if not request:
        raise UpgradeError('no request: pass --request, or keep the manifest')
    if request.get('context', {}).get('project_name') != project:
        raise UpgradeError(f"the request builds {request.get('context', {}).get('project_name')!r}, not {project!r}")
    old = manifest['files'] if manifest else generated_files(Path(baseline), project)

    report = {'from': (manifest or {}).get('version', 'baseline'), 'to': a2c_version(), 'replaced': [],
              'added': [], 'unchanged': [], 'yours': [], 'kept_deleted': [], 'no_longer_generated': []}
    patches: List[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        result = build(copy.deepcopy(request), Path(tmp))
        if not result.get('success'):
            raise UpgradeError(f"regeneration failed: {result.get('errors')}")
        new = generated_files(Path(tmp), project)
        for rel, new_hash in new.items():
            current, fresh = repo / rel, Path(tmp) / rel
            old_hash = old.get(rel)
            if not current.exists():
                if old_hash is None:
                    current.parent.mkdir(parents=True, exist_ok=True)
                    current.write_bytes(fresh.read_bytes())
                    report['added'].append(rel)
                else:
                    report['kept_deleted'].append(rel)          # you deleted it: it stays deleted
                continue
            current_hash = sha(current)
            if current_hash == new_hash:
                report['unchanged'].append(rel)
            elif old_hash == new_hash:
                report['unchanged'].append(rel)                  # the generator's output did not change: yours stays
            elif old_hash is not None and current_hash == old_hash:
                current.write_bytes(fresh.read_bytes())          # untouched by you: replaced
                report['replaced'].append(rel)
            else:                                                # changed by you: a patch to review
                before = Path(baseline) / rel if baseline and (Path(baseline) / rel).is_file() else current
                if before != current and sha(before) == new_hash:
                    report['unchanged'].append(rel)              # the generator did not change it
                    continue
                label = ('from the old generated file: apply it to your file with '
                         '`git apply --reject a2c-upgrade.patch` (hunks that meet your changes go to .rej files)'
                         if before != current else 'from YOUR file: applying it would discard your changes; '
                         'take only the parts you want')
                # git apply ignores text before the first '---' line of each file's diff
                patches.append(f'A2C {report["to"]} upgrade of {rel}, {label}\n' + ''.join(
                    difflib.unified_diff(_text(before), _text(fresh), f'a/{rel}', f'b/{rel}')))
                report['yours'].append(rel)
        report['no_longer_generated'] = sorted(set(old) - set(new))
        patch = repo / 'a2c-upgrade.patch'
        if patches:
            patch.write_text('\n'.join(patches), encoding='utf-8')
            report['patch'] = str(patch)
        elif patch.exists():
            patch.unlink()
        write_manifest_from(project_dir, request, new)
    return report


def write_manifest_from(project_dir: Path, request: Dict[str, Any], files: Dict[str, str]) -> None:
    path = Path(project_dir) / MANIFEST
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({'generator': 'a2c-framework', 'version': a2c_version(),
                                'request': clean_request(request), 'files': files}, indent=2, sort_keys=True) + '\n',
                    encoding='utf-8')
